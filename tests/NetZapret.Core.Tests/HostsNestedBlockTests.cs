using NetZapret.Proxy;
using Xunit;

namespace NetZapret.Core.Tests;

/// <summary>
/// Блок Zapret GUI внутри нашего блока hosts.
/// </summary>
/// <remarks>
/// Zapret GUI ставит свой блок перед первой строкой-записью, а первая запись
/// файла — наша (его <c>_insert_managed_hosts_block</c>, прочитано 19.10).
/// Так было у владельца 19.10: строки 136–190 внутри 131–275, и до правки
/// первое же закрепление стирало разметку Zapret GUI, присваивая его записи.
/// </remarks>
public sealed class HostsNestedBlockTests : IDisposable
{
    private readonly string _file = Path.Combine(
        Path.GetTempPath(), $"netzapret-hosts-nested-{Guid.NewGuid():N}.txt");

    public void Dispose()
    {
        foreach (var f in Directory.GetFiles(
            Path.GetDirectoryName(_file)!, Path.GetFileNameWithoutExtension(_file) + "*"))
        {
            try { File.Delete(f); } catch (Exception) { }
        }
    }

    private const string GuiBegin = "# >>> zapretgui:hosts managed begin >>>";
    private const string GuiEnd = "# <<< zapretgui:hosts managed end <<<";

    private static readonly string Sample = $"""
        # Copyright (c) Microsoft Corp.
        # >>> netzapret begin >>>
        # Сайт — Claude
        # Записи ведёт NetZapret.

        {GuiBegin}
        # Generated by ZapretGUI. Do not edit this block manually.
        83.217.211.149 a-api.anthropic.com
        83.217.211.149 claude.ai
        {GuiEnd}

        83.217.211.149 claude.ai
        157.240.245.174 instagram.com # nz:desync
        # <<< netzapret end <<<

        127.0.0.1 localhost
        """;

    private void Write(string text = "") => File.WriteAllText(_file, text.Length == 0 ? Sample : text);

    private string[] Lines() => File.ReadAllLines(_file);

    private string[] GuiBlock() => Lines()
        .SkipWhile(l => l != GuiBegin)
        .TakeWhile(l => l != GuiEnd)
        .Append(GuiEnd)
        .ToArray();

    [Fact]
    public void Records_of_the_nested_block_are_not_ours()
    {
        Write();

        Assert.DoesNotContain("a-api.anthropic.com", HostsEditor.Pins(_file).Keys);
        Assert.DoesNotContain("a-api.anthropic.com", HostsEditor.PinsAll(_file).Keys);
        Assert.Contains("claude.ai", HostsEditor.Pins(_file).Keys);
        Assert.Equal(["instagram.com"], HostsEditor.DesyncPins(_file));
    }

    [Fact]
    public void Pinning_keeps_the_nested_block_verbatim_and_above_ours()
    {
        Write();
        var before = GuiBlock();

        HostsEditor.Pin(new Dictionary<string, string> { ["new.example"] = "1.2.3.4" }, _file);

        var lines = Lines().ToList();

        Assert.Equal(before, GuiBlock());
        Assert.True(lines.IndexOf(GuiEnd) < lines.IndexOf(HostsEditor.BlockBegin));

        // Вложенным он больше не стоит, и его записи нашими не стали.
        Assert.DoesNotContain("a-api.anthropic.com", HostsEditor.Pins(_file).Keys);
        Assert.Contains("new.example", HostsEditor.Pins(_file).Keys);

        // Разрешение имён не изменилось: первой по-прежнему идёт строка Zapret GUI.
        var first = HostsTable.Read(_file).First(r => r.Name == "claude.ai");
        Assert.Equal("Zapret GUI", first.Source);
    }

    [Fact]
    public void Our_block_stays_where_it_was()
    {
        Write();

        HostsEditor.Pin(new Dictionary<string, string> { ["new.example"] = "1.2.3.4" }, _file);

        var lines = Lines();
        Assert.Equal("# Copyright (c) Microsoft Corp.", lines[0]);
        Assert.Equal("127.0.0.1 localhost", lines[^1]);
    }

    [Fact]
    public void Pinning_again_does_not_pile_up_blank_lines()
    {
        Write();

        HostsEditor.Pin(new Dictionary<string, string> { ["one.example"] = "1.2.3.4" }, _file);
        int count = Lines().Length;

        HostsEditor.Pin(new Dictionary<string, string> { ["one.example"] = "1.2.3.5" }, _file);
        HostsEditor.Pin(new Dictionary<string, string> { ["one.example"] = "1.2.3.6" }, _file);

        Assert.Equal(count, Lines().Length);
    }

    [Fact]
    public void Unpinning_everything_leaves_the_nested_block()
    {
        Write();
        var before = GuiBlock();

        HostsEditor.Unpin(["claude.ai", "instagram.com"], _file);

        Assert.DoesNotContain(HostsEditor.BlockBegin, File.ReadAllText(_file));
        Assert.Equal(before, GuiBlock());
    }

    [Fact]
    public void Removing_our_last_name_leaves_the_nested_block()
    {
        Write();
        var before = GuiBlock();

        var ours = HostsTable.Read(_file).Where(r => r.Ours).Select(r => (r.Line, r.Name)).ToList();
        HostsEditor.RemoveNames(ours, _file);

        Assert.DoesNotContain(HostsEditor.BlockBegin, File.ReadAllText(_file));
        Assert.Equal(before, GuiBlock());
    }

    [Fact]
    public void A_first_foreign_block_is_not_the_header()
    {
        // Без шапки и с блоком Zapret GUI первым наш блок встал бы внутрь
        // чужого: шапкой считались все комментарии подряд.
        Write($"""
            {GuiBegin}
            # Generated by ZapretGUI. Do not edit this block manually.
            83.217.211.149 claude.ai
            {GuiEnd}
            """);

        HostsEditor.Pin(new Dictionary<string, string> { ["new.example"] = "1.2.3.4" }, _file);

        var lines = Lines().ToList();
        Assert.True(lines.IndexOf(HostsEditor.BlockEnd) < lines.IndexOf(GuiBegin));
        Assert.Equal("Zapret GUI", HostsTable.Read(_file).Single(r => r.Name == "claude.ai").Source);
    }

    [Fact]
    public void Our_line_after_the_nested_block_is_still_ours_for_repeats()
    {
        // До 19.10 закрытие вложенного блока обнуляло блок, и строка нашего
        // ниже считалась строкой вне блоков — «Убрать повторы» могла её удалить.
        Write();

        var report = HostsDuplicates.Find(_file);
        var repeat = Assert.Single(report.Repeats);

        Assert.Equal("claude.ai", repeat.Name);
        Assert.Equal(HostsTable.OurSource, repeat.Block);
        Assert.Empty(report.Removable);
    }
}
