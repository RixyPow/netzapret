namespace NetZapret.Supervisor;

/// <summary>
/// Что супервизор делает с исходом функциональной проверки.
/// </summary>
/// <remarks>
/// <para>
/// Вынесено из цикла присмотра отдельно, потому что это единственная
/// его часть, которую можно проверить, не поднимая настоящих процессов.
/// Остальное — запуск, убийство, ожидание портов — без живого движка
/// не проверяется, и правило, спрятанное там, осталось бы без надзора.
/// </para>
/// <para>
/// Правило появилось по замеру 20.09 и стоило владельцу дня работы:
/// семь из девяти серверов его подписки перестали отвечать, проверка
/// трафика честно проваливалась, и супервизор гасил исправный движок
/// каждые полминуты. Восемнадцать секунд тишины, подъём в ту же мёртвую
/// подписку, и снова — жалоба звучала как «туннель отваливается
/// на пару секунд».
/// </para>
/// </remarks>
public static class SupervisorRules
{
    /// <summary>
    /// Считается ли этот исход поводом к перезапуску.
    /// </summary>
    /// <remarks>
    /// Только сломанный движок. Мёртвый выход перезапуском не лечится:
    /// движок поднимется в ту же подписку и упрётся в то же самое,
    /// а между попытками не будет работать и то, что работало бы.
    /// </remarks>
    public static bool CountsTowardRestart(ServiceCheck check) =>
        check == ServiceCheck.Broken;

    /// <summary>
    /// Какое здоровье показывать человеку по исходу проверки.
    /// </summary>
    /// <remarks>
    /// Мёртвый выход — это <see cref="ServiceHealth.Degraded"/>, а не
    /// «здоров». Замалчивать нельзя: трафик и вправду не идёт, и человек
    /// имеет право видеть это в окне, даже если чинить должны не мы.
    /// </remarks>
    public static ServiceHealth HealthFor(ServiceCheck check) => check switch
    {
        ServiceCheck.Healthy => ServiceHealth.Healthy,
        _ => ServiceHealth.Degraded,
    };
}
