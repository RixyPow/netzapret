namespace NetZapret.Core;

/// <summary>Как движок туннеля спрашивает имена (<see cref="AppSettings.DnsVia"/>).</summary>
public enum DnsRoute
{
    /// <summary>Сам решает: напрямую, а когда резолвер напрямую не отвечает, — через туннель (с 19.10).</summary>
    Auto,

    /// <summary>Напрямую, своим соединением по DoH.</summary>
    Direct,

    /// <summary>Внутри туннеля, всегда.</summary>
    Tunnel,
}

/// <summary>Слова для выбора пути DNS — одни в окне, отчёте и nz.</summary>
public static class DnsRoutes
{
    public static string Word(DnsRoute route) => route switch
    {
        DnsRoute.Direct => "напрямую",
        DnsRoute.Tunnel => "через туннель",
        _ => "авто",
    };

    /// <summary>
    /// Чем платит выбранный путь — при этих режиме и пути. Одни слова на вкладке
    /// DNS и в мастере первого запуска (владелец 06.10: выбор DNS — и в мастер).
    /// </summary>
    /// <remarks>
    /// <para>
    /// У каждого пути своя цена, и названа она честно. Без туннеля
    /// «через туннель» значит «через движок»: запросы Windows ловит
    /// sing-box без выхода (<see cref="AppSettings.NeedsDnsEngine"/>); «авто»
    /// без туннеля — то же, что «напрямую».
    /// </para>
    /// <para>
    /// Через туннель спрашиваются только имена мимо VPN: именам «через VPN»
    /// движок выдаёт подменные адреса. И все они получают адреса рядом
    /// с выходом туннеля, а соединяются напрямую. Замер 06.10, выход в Италии:
    /// i.ytimg.com по адресам от DNS через туннель — TCP 59–63 мс, TLS 141–151 мс,
    /// по адресам от прямого DoH — 30–34 и 65–73 мс.
    /// </para>
    /// </remarks>
    public static string Explain(AppSettings settings)
    {
        if (settings.UseRouterDns)
            return $"DNS роутера: {settings.RouterDnsAddress}:53 по UDP напрямую в локальную сеть. "
                + "DoH-автовыбор и путь через VPN не используются. Прямым доменам выдаются реальные IP; "
                + "для явно проксируемых доменов сохраняется FakeIP. Браузерный DoH и DNS-кэш могут обходить этот путь.";
        if (!settings.NeedsProxy && settings.NeedsDesync)
        {
            return settings.DnsVia == DnsRoute.Tunnel
                ? "Туннель не поднимается, поэтому запросы Windows забирает движок без выхода "
                  + "и спрашивает выбранный резолвер по DoH напрямую. Так открытый DNS, который "
                  + "часть операторов подменяет, до программ не доходит. VPN при этом не работает."
                : "Туннель не поднимается, и имена разрешает сама Windows обычным DNS. У части "
                  + "операторов его подменяют — тогда YouTube и другие сайты не находятся вовсе, "
                  + "и десинку нечего чинить. «Через туннель» заведёт запросы в движок без VPN.";
        }

        const string far =
            " Сайты, которые идут мимо VPN, получают при этом адреса рядом с сервером VPN, "
            + "а не рядом с вами, и соединяются заметно дольше.";

        return settings.DnsVia switch
        {
            DnsRoute.Tunnel =>
                "Запросы идут внутри туннеля: оператору они неотличимы от прочего трафика "
                + "и заблокировать их отдельно нельзя. Цена — пока туннель не поднялся или если "
                + "он умер, имена не разрешаются вовсе, включая то, что работало на десинке." + far,
            DnsRoute.Direct =>
                "Запросы идут напрямую к выбранному резолверу, и сайты получают адреса рядом с вами. "
                + "Если оператор перекроет DoH — а в августе 2026 это сделали несколько российских, — "
                + "ставьте «авто» или «через туннель».",
            _ =>
                "Напрямую, пока выбранный резолвер так отвечает, — сайты получают адреса рядом с вами. "
                + "Перекроет оператор DoH — тот же резолвер спрашивается обычным DNS по TCP, он у "
                + "операторов обычно не тронут; замолчит и он — запросы уйдут в туннель и вернутся, "
                + "когда прямой путь оживёт. Переключает программа сама, без перезапуска движков; пока "
                + "запросы в туннеле, сайты мимо VPN получают адреса рядом с сервером VPN и соединяются дольше.",
        };
    }

    /// <summary>Разбор слова из nz: «авто», «напрямую», «туннель» и английские.</summary>
    public static DnsRoute? Parse(string? word) => word?.Trim().ToLowerInvariant() switch
    {
        "авто" or "auto" => DnsRoute.Auto,
        "напрямую" or "direct" => DnsRoute.Direct,
        "туннель" or "через туннель" or "tunnel" => DnsRoute.Tunnel,
        _ => null,
    };
}
