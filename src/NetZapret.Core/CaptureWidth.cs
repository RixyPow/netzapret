namespace NetZapret.Core;

/// <summary>
/// Сколько трафика отдавать десинку на разбор — ширина перехвата WinDivert.
/// </summary>
/// <remarks>
/// <para>
/// Владелец 03.10, по замеру того же дня: новое соединение через winws2 стоит
/// ему 28–38 мс процессора в одном потоке, и пачка новых потоков стопорит
/// соседние — игровой UDP в том числе, при любом маршруте. Что под перехват
/// не попало, идёт обычным путём и не стоит ничего.
/// </para>
/// <para>
/// Уровни — как режимы WinDivert у Zapret GUI (вики, «Zapret2/windivert»):
/// «аккуратный» на 80 и 443 и «агрессивный» на все порты; между ними —
/// то, что задал автор пресета.
/// </para>
/// </remarks>
public enum CaptureWidth
{
    /// <summary>Как задано в пресете — его ключами <c>--wf-tcp-out</c> и <c>--wf-udp-out</c>.</summary>
    Preset = 0,

    /// <summary>
    /// Только сайты: TCP 80 и 443, UDP 443 (QUIC). STUN, обнаружение адреса
    /// Discord и рукопожатия WireGuard ловятся по содержимому, как в пресете.
    /// </summary>
    Sites = 1,

    /// <summary>Всё: TCP 80 и 443–65535, UDP 443–65535 — чтобы подобрать стратегию.</summary>
    All = 2,
}
