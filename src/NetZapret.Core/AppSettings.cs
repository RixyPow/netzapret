using System.Text;
using System.Text.Encodings.Web;
using System.Text.Json;
using System.Text.Json.Serialization;
using NetZapret.Core.Rules;

namespace NetZapret.Core;

/// <summary>
/// Выбор пользователя: что запускать и как.
/// </summary>
/// <remarks>
/// Появились ради меню. До него режим жил в файле правил, а пресет и сервер —
/// в аргументах командной строки, и запомнить выбор между запусками было негде.
/// Здесь же лежит то, что человек выбирает руками; сами правила остаются
/// в своём YAML и этим файлом не переписываются.
/// </remarks>
public sealed record AppSettings
{
    /// <summary>Ссылка на подписку.</summary>
    public string? SubscriptionUrl { get; init; }

    /// <summary>
    /// Базовый файл правил. Поверх него накладывается пользовательский слой
    /// из <see cref="Rules.UserRulesFile.DefaultPath"/>.
    /// </summary>
    /// <remarks>
    /// По умолчанию — рабочий <c>rules.yaml</c>, а не <c>rules.example.yaml</c>.
    /// Ссылка на пример однажды уже стоила поломки: конфиг пересобрался
    /// из примера, и Telegram потерял маршрут через VPN.
    /// </remarks>
    public string RulesPath { get; init; } = Path.Combine("config", "rules.yaml");

    /// <summary>
    /// Режим работы. Перекрывает значение из файла правил.
    /// </summary>
    /// <remarks>
    /// Перекрытие, а не правка YAML: файл правил пишет человек, там комментарии
    /// и порядок строк, и лезть в него из меню значит рано или поздно его испортить.
    /// </remarks>
    public OperatingMode Mode { get; init; } = OperatingMode.Selective;

    /// <summary>Название пресета Zapret; <c>null</c> — не запускать десинк.</summary>
    /// <remarks>
    /// <para>
    /// По умолчанию — Universal V9: он идёт в сборке и покрывает больше всего
    /// случаев. Пустое значение означало бы, что при первом запуске десинк
    /// молча не работает, а человек об этом узнаёт по неоткрывающимся сайтам.
    /// Если такого пресета нет, обзор состояния скажет об этом прямо.
    /// </para>
    /// <para>
    /// Был V8, стал V9: тот же набор плюс семь секций с рецептами, которые
    /// владелец подобрал вручную и проверил на живой сети — Valheim,
    /// Instagram, Facebook, SoundCloud, Speedtest, Medium, VirusTotal.
    /// Прежде они жили переопределениями в rules.user.yaml и терялись
    /// при сбросе настроек; теперь это часть пресета.
    /// </para>
    /// <para>
    /// Смена касается только новых установок. Настройки переживают обновление
    /// намеренно — в них работа человека, — поэтому у тех, кто уже запускался,
    /// останется прежний выбор, и меняется он в меню.
    /// </para>
    /// </remarks>
    public string? PresetName { get; init; } = DefaultPresetName;

    public const string DefaultPresetName = "Universal V9";

    /// <summary>Тег сервера либо <c>null</c> для автоподбора по задержке.</summary>
    public string? PreferredServer { get; init; }

    public string ProxyConfigPath { get; init; } = Path.Combine("runtime", "singbox.json");

    /// <summary>Заводить в туннель только трафик прокси.</summary>
    public bool ProxyOnly { get; init; } = true;

    /// <summary>Проверять не только порт, но и реальный проход трафика.</summary>
    public bool VerifyTraffic { get; init; }

    /// <summary>
    /// Разрешать имена через туннель, а не напрямую.
    /// </summary>
    /// <remarks>
    /// <para>
    /// Пригодится, если оператор перекроет DoH: запрос внутри туннеля от
    /// прочего трафика неотличим, и заблокировать его отдельно нельзя.
    /// В августе 2026 такие ограничения появились у нескольких российских
    /// операторов.
    /// </para>
    /// <para>
    /// Выключено по умолчанию: включённое, оно ставит разрешение имён
    /// в зависимость от туннеля, и пока тот не поднялся, не открывается
    /// ничего — включая то, что работало на десинке. Включать, когда прямой
    /// DoH уже отказал, а не заранее.
    /// </para>
    /// </remarks>
    public bool DnsThroughTunnel { get; init; }

    /// <summary>Апстрим DNS; адресом, не именем.</summary>
    public string DnsServer { get; init; } = "8.8.8.8";

    /// <summary>
    /// Вести журнал супервизора.
    /// </summary>
    /// <remarks>
    /// По умолчанию включён, и выключать его стоит с осторожностью: без
    /// журнала разбор сбоя сводится к догадкам. Выключатель заведён для тех,
    /// кого смущает рост файла — winws2 пишет строку на соединение.
    /// </remarks>
    public bool LogsEnabled { get; init; } = true;

    /// <summary>
    /// Предлагать перезапуск Discord после смены маршрута.
    /// </summary>
    /// <remarks>
    /// Discord запоминает голосовые серверы на сеанс, и до перезапуска ходит
    /// по-старому. Само собой это не делается никогда: перезапуск посреди
    /// звонка хуже задержки с применением.
    /// </remarks>
    public bool OfferDiscordRestart { get; init; }

    /// <summary>
    /// Держать автоподбор сервера подальше от отечественных выходов.
    /// </summary>
    /// <remarks>
    /// Включено по умолчанию. Автоподбор идёт по задержке и потому всегда
    /// сползает на ближайший сервер — свой же, — а через него не работает
    /// ровно то, ради чего туннель обычно и нужен: сервисы, закрывающиеся
    /// от страны. Выбрать отечественный вручную это не мешает.
    /// </remarks>
    public bool ForeignExitsOnly { get; init; } = true;

    /// <summary>
    /// Подмешивать выходы Cloudflare WARP к серверам действующей подписки.
    /// </summary>
    /// <remarks>
    /// <para>
    /// Именно подмешивать, а не подменять. Отдельной подпиской WARP быть
    /// не может: конфиг движка собирается по одной ссылке, и выбор выхода
    /// WARP делал действующей его — то есть запасной выход занимал место
    /// основного вместо того, чтобы его страховать. Ровно наоборот тому,
    /// ради чего он заведён.
    /// </para>
    /// <para>
    /// Включённый, он даёт автоподбору ещё одного кандидата, который
    /// не кончается и не истекает. Пока живы серверы подписки, выбор всё равно
    /// падёт на них — они быстрее; когда лягут, останется он.
    /// </para>
    /// <para>
    /// Выключен по умолчанию: WARP выпускает трафик в ближайшей стране,
    /// и на российском подключении это Москва. От блокировок оператора
    /// он спасает, от отказов по стране — нет.
    /// </para>
    /// </remarks>
    public bool WarpEnabled { get; init; }

    /// <summary>
    /// Уводить трафик мимо туннеля, когда его выходы перестали отвечать.
    /// </summary>
    /// <remarks>
    /// <para>
    /// Жалоба владельца 20.09: «при падении серверов сделать так, чтоб вся
    /// остальная сеть не страдала». Движок при мёртвой подписке жив и трафик
    /// исправно принимает — а наружу тот не выходит; в режиме «всё через VPN»
    /// это вся сеть целиком. Обход переключает группу выбора на прямой выход
    /// и возвращает обратно, как только выход оживёт.
    /// </para>
    /// <para>
    /// <b>Это компромисс, а не бесплатное улучшение.</b> Трафик, который
    /// просили вести через туннель, пойдёт мимо — открыто и с домашнего
    /// адреса. Для обхода блокировок цена приемлема: закрытый сайт просто
    /// останется закрытым. Для скрытности — нет, и потому настройка есть.
    /// </para>
    /// <para>
    /// Включён по умолчанию, потому что беда, от которой он спасает, у людей
    /// случается, а скрытность программа и так нигде не обещает: она про
    /// обход блокировок. Срабатывание говорится вслух — в журнале и
    /// в состоянии, — а не делается тихо.
    /// </para>
    /// </remarks>
    public bool BypassWhenTunnelDead { get; init; } = true;

    /// <summary>
    /// Палитра окна: <c>dark</c> либо <c>light</c>.
    /// </summary>
    /// <remarks>
    /// Строкой, а не логическим полем: тем может стать больше двух, и тогда
    /// <c>LightTheme: false</c> пришлось бы читать как «какая-то из
    /// остальных». Неизвестное значение считается тёмной темой — она была
    /// единственной, и старые настройки не должны ломаться.
    /// </remarks>
    public string? Theme { get; init; }

    /// <summary>
    /// Какой набор адресов брать из каталога Zapret.
    /// </summary>
    /// <remarks>
    /// Профили — конкурирующие наборы чужих прокси для одних и тех же имён.
    /// Работают по-разному и живут ровно столько, сколько живёт узел за ними,
    /// поэтому выбор остаётся за человеком, а не делается «самым свежим».
    /// </remarks>
    public string? AddressProfile { get; init; }

    /// <summary>
    /// Сервисы каталога, которым выдаются адреса.
    /// </summary>
    /// <remarks>
    /// Поимённо, а не весь каталог разом. В нём восемьсот доменов, и выдать
    /// адрес прокси тому, что и так работает, значит увести рабочий трафик
    /// через чужой узел — медленнее, и сломается вместе с ним.
    /// </remarks>
    public IReadOnlyList<string> AddressServices { get; init; } = [];

    /// <summary>Проверять наличие новой версии при запуске.</summary>
    /// <remarks>
    /// Только проверять. Установка — отдельное действие с отдельным согласием:
    /// подменять работающий обход молча нельзя.
    /// </remarks>
    public bool CheckForUpdates { get; init; } = true;

    /// <summary>
    /// Сценарий первого запуска показан и закрыт.
    /// </summary>
    /// <remarks>
    /// <para>
    /// Без этого поля программа не могла бы отличить человека, который
    /// впервые открыл окно, от того, кто уже всё настроил и просто зашёл
    /// на «Главную». Файла настроек ещё нет — значение по умолчанию
    /// <c>false</c>, и мастер показывается.
    /// </para>
    /// <para>
    /// Ставится и при пропуске мастера, не только при его завершении:
    /// «пропустить» — тоже решение, и показывать мастер второй раз человеку,
    /// который его уже закрыл, значит не уважать этот выбор.
    /// </para>
    /// </remarks>
    public bool OnboardingDone { get; init; }

    public static string DefaultPath => Path.Combine("config", "netzapret.json");

    private static readonly JsonSerializerOptions Options = new()
    {
        WriteIndented = true,
        Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping,
        DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull,
        Converters = { new JsonStringEnumConverter() },
    };

    public static AppSettings Load(string? path = null)
    {
        var target = path ?? DefaultPath;

        if (!File.Exists(target))
            return new AppSettings();

        try
        {
            return JsonSerializer.Deserialize<AppSettings>(File.ReadAllText(target), Options)
                ?? new AppSettings();
        }
        catch (Exception)
        {
            // Испорченный файл настроек не повод не запуститься: берём значения
            // по умолчанию, а сохранение перезапишет его корректным.
            return new AppSettings();
        }
    }

    public void Save(string? path = null)
    {
        var target = path ?? DefaultPath;
        var directory = Path.GetDirectoryName(target);

        if (!string.IsNullOrEmpty(directory))
            Directory.CreateDirectory(directory);

        File.WriteAllText(target, JsonSerializer.Serialize(this, Options), new UTF8Encoding(false));
    }

    /// <remarks>
    /// Выборочный без выхода называется тем, чем он на деле и является.
    /// Иначе выходит обман в одну строку: человек читает «выборочно»,
    /// ждёт, что часть имён пойдёт через VPN, а туннеля нет вовсе — и
    /// не понимает, почему правило «через VPN» ничего не меняет.
    /// </remarks>
    public string DescribeMode() => Mode switch
    {
        OperatingMode.Off => "выключено",
        OperatingMode.DesyncOnly => "только десинк",
        OperatingMode.ProxyAll => "всё через VPN, кроме РФ",
        OperatingMode.ProxyStrict => "всё через VPN без исключений",
        OperatingMode.Selective when !HasTunnelExit => "только десинк — VPN не задан",
        _ => "выборочно",
    };

    /// <summary>Нужен ли в этом режиме туннель.</summary>
    /// <remarks>
    /// <para>
    /// Поднимать sing-box там, где он никуда не ведёт, значит без причины
    /// держать TUN и путать поиск неисправностей: адаптер есть, маршруты
    /// стоят, а трафик через них не идёт.
    /// </para>
    /// <para>
    /// Не сохраняется: выводится из режима. Попав в файл, такое поле выглядит
    /// настройкой — его правят, а оно не действует, потому что при чтении
    /// пересчитывается заново.
    /// </para>
    /// </remarks>
    [JsonIgnore]
    public bool NeedsProxy => Mode switch
    {
        // Выборочный без выхода — это просто десинк, и поднимать ради него
        // TUN незачем. В этом режиме всё и так идёт мимо туннеля, кроме
        // выведенных в него правилами; без подписки выводить некуда,
        // и правила «через VPN» молча не срабатывают — ровно как если бы
        // человек выбрал «только десинк» руками.
        //
        // Прежде здесь смотрели на один режим, и без подписки не поднималось
        // НИЧЕГО: сборка конфига отвечала «Подписка не задана», запуск
        // отказывался, и десинк не получал своего шанса. Программа без
        // подписки выглядела нерабочей целиком, хотя половина её работы
        // подписки не требует вовсе.
        OperatingMode.Selective => HasTunnelExit,

        // А вот «всё через VPN» без выхода молча превратилось бы в «ничего
        // через VPN» — то есть в обратное обещанному, и трафик, который
        // человек просил спрятать, пошёл бы открыто. Здесь отказ громче
        // и честнее: пусть сборка конфига скажет, чего не хватает.
        OperatingMode.ProxyAll or OperatingMode.ProxyStrict => true,

        _ => false,
    };

    /// <summary>
    /// Есть ли куда заворачивать трафик.
    /// </summary>
    /// <remarks>
    /// WARP считается выходом наравне с подпиской: он и заведён затем, чтобы
    /// работать, когда подписки нет. Прежде сборка конфига отказывалась
    /// при пустой ссылке, не глядя на выключатель, и включённый WARP
    /// в одиночку не поднимался вовсе.
    /// </remarks>
    [JsonIgnore]
    public bool HasTunnelExit => !string.IsNullOrWhiteSpace(SubscriptionUrl) || WarpEnabled;

    /// <summary>Нужен ли в этом режиме десинк.</summary>
    [JsonIgnore]
    public bool NeedsDesync => Mode is not OperatingMode.Off && PresetName is not null;

    public string DescribeServer() => PreferredServer ?? "авто (по задержке)";

    public string DescribePreset() => PresetName ?? "не запускать";
}
