    public static string DefaultPath => Path.Combine("config", "netzapret.json");

    private static readonly JsonSerializerOptions Options = new()
    {
        WriteIndented = true,
        Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping,
        DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull,
        Converters = { new JsonStringEnumConverter() },
    };

    /// <summary>Как прошло чтение настроек.</summary>
    public enum ReadResult
    {
        /// <summary>Прочитаны.</summary>
        Read,

        /// <summary>Файла нет — свежая установка.</summary>
        Missing,

        /// <summary>Файл есть, но не прочитался: занят либо испорчен.</summary>
        Unreadable,
    }

    public static AppSettings Load(string? path = null) => TryLoad(path, out _);

    /// <summary>
    /// Настройки и то, как они прочитались.
    /// </summary>
    /// <remarks>
    /// <para>
    /// Нужно тем, кому «файла нет» и «файл не прочитался» — разные ответы.
    /// Владелец 30.09: «почему у меня уже второй раз программа первого запуска
    /// появляется». Мастер показывался, когда <see cref="OnboardingDone"/>
    /// читалось как false, а читалось оно так всякий раз, когда чтение
    /// не удавалось: вместо настроек возвращались значения по умолчанию.
    /// Чем именно не удалось чтение у владельца, не установлено — в журнале
    /// причина не писалась.
    /// </para>
    /// <para>
    /// Занятый файл — не испорченный: окно, надзор и nz читают и пишут его
    /// из разных процессов. Такое чтение повторяется несколько раз с короткой
    /// паузой, прежде чем сдаться.
    /// </para>
    /// </remarks>
    /// <summary>
    /// Имя выхода WARP — то же, что <c>Warp.MasqueTag</c>: библиотека настроек
    /// о подписках не знает, а сверить выбор с ним надо здесь.
    /// </summary>
    private const string WarpTag = "Cloudflare WARP";

    /// <summary>
    /// Переведён ли WARP в «выбор пути» (01.10); <c>null</c> — настройки старше.
    /// </summary>
    public bool? WarpIsPath { get; init; }

    /// <summary>
    /// Разовый перевод WARP из запасного в выбор пути (01.10).
    /// </summary>
    /// <remarks>
    /// <para>
    /// До 01.10 включённый WARP подмешивался к подпискам запасным; с 01.10 он
    /// ставит их на паузу. Прочитанный как есть, старый выключатель увёл бы
    /// в WARP целиком каждого, кто включал его запасным, — молча, с выходом
    /// в Москве вместо его серверов.
    /// </para>
    /// <para>
    /// Поэтому один раз: WARP был выбран сервером — он и есть путь, а выбор
    /// снимается (с выключением WARP туннель вернётся к автоподбору подписок);
    /// включён лишь запасным — выключается. Дальше выключатель значит то,
    /// что значит.
    /// </para>
    /// </remarks>
    private static AppSettings WarpAsPath(AppSettings read)
    {
        if (read.WarpIsPath == true)
            return read;

        bool chosen = read.PreferredServer == WarpTag;

        return read with
        {
            WarpEnabled = chosen || (read.WarpEnabled && !read.HasSubscriptionExit),
            PreferredServer = chosen ? null : read.PreferredServer,
            WarpIsPath = true,
        };
    }

    /// <summary>
    /// Выключен ли game filter разовым переводом (01.10); <c>null</c> — настройки старше.
    /// </summary>
    public bool? GameFilterReset { get; init; }

    /// <summary>
    /// Разовое выключение game filter у всех (владелец, 01.10).
    /// </summary>
    /// <remarks>
    /// Выключен по умолчанию он был и прежде, но включали его многие —
    /// советом из обсуждений, — и забывали. Цена измерена: при включённом
    /// десинк подделывал начало игрового UDP Valorant по сетям Riot из
    /// ipset-all (30.09), и под подозрением пинг Genshin (обсуждение #12).
    /// Один раз: включивший его после перевода сохраняет и отметку,
    /// и выключатель дальше значит то, что значит.
    /// </remarks>
    private static AppSettings GameFilterOnce(AppSettings read) =>
        read.GameFilterReset == true ? read : read with { GameFilter = false, GameFilterReset = true };

    /// <summary>
    /// Настройки с нуля — с отметками разовых переводов.
    /// </summary>
    /// <remarks>
    /// Без отметок первое сохранение таких настроек выглядело бы старым файлом,
    /// и следующее чтение перевело бы их ещё раз: включённый человеком game
    /// filter молча выключился бы.
    /// </remarks>
    public static AppSettings Fresh => new() { WarpIsPath = true, GameFilterReset = true };

    /// <summary>Есть ли выход кроме WARP: подписка или отдельные ключи.</summary>
    [JsonIgnore]
    private bool HasSubscriptionExit => !string.IsNullOrWhiteSpace(SubscriptionUrl) || KeysEnabled;

    public static AppSettings TryLoad(string? path, out ReadResult result)
    {
        var target = path ?? DefaultPath;

        if (!File.Exists(target))
        {
            result = ReadResult.Missing;
            return Fresh;
        }

        string? text = null;

        for (int attempt = 0; attempt < 5 && text is null; attempt++)
        {
            try
            {
                text = File.ReadAllText(target);
            }
            catch (IOException)
            {
                Thread.Sleep(60);
            }
            catch (UnauthorizedAccessException)
            {
                Thread.Sleep(60);
            }
        }

        if (text is null)
        {
            result = ReadResult.Unreadable;
            return Fresh;
        }

        try
        {
            var read = JsonSerializer.Deserialize<AppSettings>(text, Options)
                ?? throw new JsonException("пустой файл настроек");

            result = ReadResult.Read;

            // Режим сводится к выключателям при каждом чтении. 0.7.0 писала
            // «выборочный» рядом с включённым «игнорировать исключения»:
            // тогда настройка режима не меняла. С 23.09 меняет, и прочитанный
            // как есть записанный режим развёл бы окно и движок — окно
            // показывало бы «всё в туннель», а конфиг собирался бы по книге.
            //
            // 8.8.8.8 переводится на 8.8.4.4: это тот же Google с тем же
            // сертификатом, а записан он почти у всех потому, что стоял
            // по умолчанию, а не потому, что выбран. Без перевода смена
            // умолчания 27.09 досталась бы только новым установкам.
            return GameFilterOnce(WarpAsPath(read with
            {
                Mode = read.Engines.Mode,
                DnsServer = read.DnsServer == "8.8.8.8" ? GoogleDns : read.DnsServer,
            }));
        }
        catch (Exception)
        {
            // Испорченный файл настроек не повод не запуститься: берём значения
            // по умолчанию, а сохранение перезапишет его корректным.
            result = ReadResult.Unreadable;
            return Fresh;
        }
    }

    /// <summary>
    /// Записывает настройки целиком и разом.
    /// </summary>
    /// <remarks>
    /// Через временный файл и подмену: прежняя запись поверх открытого файла
    /// сперва обрезала его до нуля, и чтение из другого процесса в это мгновение
    /// получало пустоту — то есть настройки по умолчанию, вплоть до мастера
    /// первого запуска (30.09). Подмена файла на Windows падает, пока его держит
    /// читающий, — поэтому несколько попыток.
    /// </remarks>
    public void Save(string? path = null)
    {
        var target = path ?? DefaultPath;
        var directory = Path.GetDirectoryName(target);

        if (!string.IsNullOrEmpty(directory))
            Directory.CreateDirectory(directory);

        var temp = target + ".tmp";

        File.WriteAllText(temp, JsonSerializer.Serialize(this, Options), new UTF8Encoding(false));

        for (int attempt = 0; ; attempt++)
        {
            try
            {
                File.Move(temp, target, overwrite: true);
                return;
            }
            catch (Exception ex) when (ex is IOException or UnauthorizedAccessException && attempt < 9)
            {
                Thread.Sleep(50);
            }
        }
    }

    /// <remarks>
    /// Выборочный без выхода называется тем, чем он на деле и является.
    /// Иначе выходит обман в одну строку: человек читает «выборочно»,
    /// ждёт, что часть имён пойдёт через VPN, а туннеля нет вовсе — и
    /// не понимает, почему правило «через VPN» ничего не меняет.
    /// </remarks>
    public string DescribeMode() => Mode switch
    {
        OperatingMode.Off => "выключено",
        OperatingMode.DesyncOnly => "только десинк",
        OperatingMode.ProxyAll => "всё через VPN, кроме РФ",
        OperatingMode.ProxyStrict => "всё через VPN без исключений",
        OperatingMode.Selective when !HasTunnelExit => "только десинк — VPN не задан",
        _ => "выборочно",
    };

    /// <summary>Нужен ли в этом режиме туннель.</summary>
    /// <remarks>
    /// <para>
    /// Поднимать sing-box там, где он никуда не ведёт, значит без причины
    /// держать TUN и путать поиск неисправностей: адаптер есть, маршруты
    /// стоят, а трафик через них не идёт.
    /// </para>
    /// <para>
    /// Не сохраняется: выводится из режима. Попав в файл, такое поле выглядит
    /// настройкой — его правят, а оно не действует, потому что при чтении
    /// пересчитывается заново.
    /// </para>
    /// </remarks>
    /// <remarks>
    /// Выключатель спрашивается первым, и это исправление 21.09. Он тогда
    /// только появился, а здесь по-прежнему спрашивался режим — и туннель
    /// поднимался бы при погашенном выключателе, потому что режим при этом
    /// остаётся «выборочным». Щелчок не делал ничего, и узнать об этом
    /// можно было бы только по живому TUN.
    /// </remarks>
    [JsonIgnore]
    public bool NeedsProxy => Engines.Tunnel && Mode switch
    {
        // Выборочный без выхода — это просто десинк, и поднимать ради него
        // TUN незачем. В этом режиме всё и так идёт мимо туннеля, кроме
        // выведенных в него правилами; без подписки выводить некуда,
        // и правила «через VPN» молча не срабатывают — ровно как если бы
        // человек выбрал «только десинк» руками.
        //
        // Прежде здесь смотрели на один режим, и без подписки не поднималось
        // НИЧЕГО: сборка конфига отвечала «Подписка не задана», запуск
        // отказывался, и десинк не получал своего шанса. Программа без
        // подписки выглядела нерабочей целиком, хотя половина её работы
        // подписки не требует вовсе.
        OperatingMode.Selective => HasTunnelExit,

        // А вот «всё через VPN» без выхода молча превратилось бы в «ничего
        // через VPN» — то есть в обратное обещанному, и трафик, который
        // человек просил спрятать, пошёл бы открыто. Здесь отказ громче
        // и честнее: пусть сборка конфига скажет, чего не хватает.
        OperatingMode.ProxyAll or OperatingMode.ProxyStrict => true,

        _ => false,
    };

    /// <summary>
    /// Есть ли куда заворачивать трафик.
    /// </summary>
    /// <remarks>
    /// WARP считается выходом наравне с подпиской: он и заведён затем, чтобы
    /// работать, когда подписки нет. Прежде сборка конфига отказывалась
    /// при пустой ссылке, не глядя на выключатель, и включённый WARP
    /// в одиночку не поднимался вовсе.
    /// </remarks>
    [JsonIgnore]
    public bool HasTunnelExit => !string.IsNullOrWhiteSpace(SubscriptionUrl) || WarpEnabled || KeysEnabled;

    /// <summary>
    /// Есть ли отдельные ключи в работе (0.9.0).
    /// </summary>
    /// <remarks>
    /// Сами ключи — в subscriptions.json рядом со ссылками: это пароли,
    /// и в настройках им не место. Здесь только признак, чтобы с одними
    /// ключами, без подписки и WARP, программа не решала, что выхода нет.
    /// Ставит его окно (SubscriptionBook); консоль ключей не читает.
    /// </remarks>
    public bool KeysEnabled { get; init; }

    /// <summary>
    /// Нужен ли десинк.
    /// </summary>
    /// <remarks>
    /// <para>
    /// По выключателю, а не по режиму, и это исправление 21.09. Прежде
    /// здесь стояло «режим не выключен и пресет задан», и выключенный
    /// десинк поднимался бы как ни в чём не бывало: режимом «туннель
    /// без десинка» оказывается ProxyAll, а условие пропускало его
    /// насквозь.
    /// </para>
    /// <para>
    /// Глубже причина в том, что сочетаний четыре, а режимов пять, и одно
    /// из сочетаний режимом не выражается вовсе — «туннель по маршрутам
    /// без десинка». Спрашивать режим о том, чего он не знает, значит
    /// получать неверный ответ молча.
    /// </para>
    /// </remarks>
    /// <remarks>
    /// С 23.09 — по <see cref="EngineChoice.DesyncRuns"/>: при игнорируемых
    /// исключениях всё уходит в туннель, и у десинка работы нет.
    /// </remarks>
    [JsonIgnore]
    public bool NeedsDesync => Engines.DesyncRuns && PresetName is not null;

    public string DescribeServer() => PreferredServer ?? "авто (по задержке)";

    public string DescribePreset() => PresetName ?? "не запускать";
