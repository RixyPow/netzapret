using System.Text;
using System.Text.Encodings.Web;
using System.Text.Json;
using System.Text.Json.Serialization;
using NetZapret.Core.Rules;

namespace NetZapret.Core;

/// <summary>
/// Выбор пользователя: что запускать и как.
/// </summary>
/// <remarks>
/// Появились ради меню. До него режим жил в файле правил, а пресет и сервер —
/// в аргументах командной строки, и запомнить выбор между запусками было негде.
/// Здесь же лежит то, что человек выбирает руками; сами правила остаются
/// в своём YAML и этим файлом не переписываются.
/// </remarks>
public sealed record AppSettings
{
    /// <summary>Ссылка на подписку.</summary>
    public string? SubscriptionUrl { get; init; }

    /// <summary>
    /// Базовый файл правил. Поверх него накладывается пользовательский слой
    /// из <see cref="Rules.UserRulesFile.DefaultPath"/>.
    /// </summary>
    /// <remarks>
    /// По умолчанию — рабочий <c>rules.yaml</c>, а не <c>rules.example.yaml</c>.
    /// Ссылка на пример однажды уже стоила поломки: конфиг пересобрался
    /// из примера, и Telegram потерял маршрут через VPN.
    /// </remarks>
    public string RulesPath { get; init; } = Path.Combine("config", "rules.yaml");

    /// <summary>
    /// Режим работы. Перекрывает значение из файла правил.
    /// </summary>
    /// <remarks>
    /// Перекрытие, а не правка YAML: файл правил пишет человек, там комментарии
    /// и порядок строк, и лезть в него из меню значит рано или поздно его испортить.
    /// </remarks>
    public OperatingMode Mode { get; init; } = OperatingMode.Selective;

    /// <summary>
    /// Поднимать ли winws2; <c>null</c> — выводится из режима.
    /// </summary>
    /// <remarks>
    /// <para>
    /// Допускает пустоту намеренно, и это устройство перехода. У людей
    /// в настройках записан режим и больше ничего; прочитав пустое поле
    /// как «выключено», мы сняли бы им десинк молча — при том, что они
    /// ничего не просили.
    /// </para>
    /// <para>
    /// Пустое значит «не задавали», и тогда ответ берётся у режима.
    /// Заполняется оно при первом же щелчке по выключателю, и с этого
    /// мгновения решает уже оно.
    /// </para>
    /// </remarks>
    public bool? DesyncEnabled { get; init; }

    /// <summary>Поднимать ли туннель; <c>null</c> — выводится из режима.</summary>
    public bool? TunnelEnabled { get; init; }

    /// <summary>
    /// Отправлять в туннель всё, включая «напрямую» и «десинк».
    /// </summary>
    /// <remarks>
    /// <para>
    /// См. <see cref="EngineChoice.IgnoreExclusions"/>. До 23.09 отменяла
    /// одно правило, на российские сети; ключ в файле остался прежним,
    /// чтобы записанный выбор не пропал при обновлении.
    /// </para>
    /// <para>
    /// Допускает пустоту наравне с прочими тремя, и это выяснилось
    /// проверкой. Прежний режим «без исключений» означал в точности эту
    /// настройку, и у того, кто им пользовался, поле не записано — а
    /// прочитанное как «выключено» вернуло бы ему российские сети
    /// напрямую, молча изменив поведение.
    /// </para>
    /// </remarks>
    [JsonPropertyName("IgnoreRussianExclusions")]
    public bool? IgnoreExclusions { get; init; }

    /// <summary>
    /// Что поднято, двумя выключателями.
    /// </summary>
    /// <remarks>
    /// Задумка владельца 21.09: вместо одного поля с пятью значениями —
    /// два выключателя движков и охват туннеля. Прежний режим остаётся
    /// и выводится отсюда: на его языке говорят конфиг движка, отчёты
    /// и правила, и переводить их все разом значило бы менять полпрограммы
    /// одной правкой.
    ///
    /// В файл не пишется: собирается из <see cref="DesyncEnabled"/>,
    /// <see cref="TunnelEnabled"/> и <see cref="IgnoreExclusions"/>, а при
    /// чтении выводится заново. Прежде блок «Engines» ложился в netzapret.json
    /// вместе с вычисляемыми TunnelTakesAll, DesyncRuns и прочими — и читался
    /// как второе, спорящее с первым место тех же настроек.
    /// </remarks>
    [JsonIgnore]
    public EngineChoice Engines
    {
        get
        {
            var fromMode = EngineChoice.FromMode(Mode);

            return new EngineChoice
            {
                Desync = DesyncEnabled ?? fromMode.Desync,
                Tunnel = TunnelEnabled ?? fromMode.Tunnel,
                IgnoreExclusions = IgnoreExclusions ?? fromMode.IgnoreExclusions,
            };
        }
    }

    /// <summary>
    /// Записывает выбор — и выключатели, и выведенный из них режим.
    /// </summary>
    /// <remarks>
    /// Режим пишется тоже, а не только выключатели. Его читают конфиг
    /// движка, отчёты и консоль, и оставленный отставшим он развёл бы
    /// показания: окно говорило бы одно, движок делал другое.
    /// </remarks>
    public AppSettings With(EngineChoice choice) => this with
    {
        Mode = choice.Mode,
        DesyncEnabled = choice.Desync,
        TunnelEnabled = choice.Tunnel,
        IgnoreExclusions = choice.IgnoreExclusions,
    };

    /// <summary>Название пресета Zapret; <c>null</c> — не запускать десинк.</summary>
    /// <remarks>
    /// <para>
    /// По умолчанию — Universal V10: он идёт в сборке и покрывает больше всего
    /// случаев. Пустое значение означало бы, что при первом запуске десинк
    /// молча не работает, а человек об этом узнаёт по неоткрывающимся сайтам.
    /// Если такого пресета нет, обзор состояния скажет об этом прямо.
    /// </para>
    /// <para>
    /// Был V8, стал V9: тот же набор плюс семь секций с рецептами, которые
    /// владелец подобрал вручную и проверил на живой сети — Valheim,
    /// Instagram, Facebook, SoundCloud, Speedtest, Medium, VirusTotal.
    /// Прежде они жили переопределениями в rules.user.yaml и терялись
    /// при сбросе настроек; теперь это часть пресета.
    /// </para>
    /// <para>
    /// Был V9, стал V10: те же секции, но имена в них идут списками.
    /// В V9 они стояли строкой <c>--hostlist-domains</c>, а она поддоменов
    /// не покрывает, и www.facebook.com проходил мимо своей секции.
    /// Плюс GitHub и приложение Bluesky, которым рецепт выбран после V9.
    /// </para>
    /// <para>
    /// Смена касается только новых установок. Настройки переживают обновление
    /// намеренно — в них работа человека, — поэтому у тех, кто уже запускался,
    /// останется прежний выбор, и меняется он в меню.
    /// </para>
    /// </remarks>
    public string? PresetName { get; init; } = DefaultPresetName;

    public const string DefaultPresetName = "Universal V10";

    /// <summary>Тег сервера либо <c>null</c> для автоподбора по задержке.</summary>
    public string? PreferredServer { get; init; }

    public string ProxyConfigPath { get; init; } = Path.Combine("runtime", "singbox.json");

    /// <summary>Заводить в туннель только трафик прокси.</summary>
    public bool ProxyOnly { get; init; } = true;

    /// <summary>Проверять не только порт, но и реальный проход трафика.</summary>
    public bool VerifyTraffic { get; init; }

    /// <summary>
    /// Разрешать имена через туннель, а не напрямую.
    /// </summary>
    /// <remarks>
    /// <para>
    /// Пригодится, если оператор перекроет DoH: запрос внутри туннеля от
    /// прочего трафика неотличим, и заблокировать его отдельно нельзя.
    /// В августе 2026 такие ограничения появились у нескольких российских
    /// операторов.
    /// </para>
    /// <para>
    /// Выключено по умолчанию: включённое, оно ставит разрешение имён
    /// в зависимость от туннеля, и пока тот не поднялся, не открывается
    /// ничего — включая то, что работало на десинке. Включать, когда прямой
    /// DoH уже отказал, а не заранее.
    /// </para>
    /// </remarks>
    public bool DnsThroughTunnel { get; init; }

    /// <summary>Апстрим DNS; адресом, не именем.</summary>
    /// <remarks>
    /// 8.8.4.4, а не 8.8.8.8: с 3 июля многие операторы закрыли 8.8.8.8
    /// по TCP — DoH и DoT, — а 8.8.4.4 оставили (вики Zapret GUI). Туннель
    /// ходит к апстриму именно по DoH, и там, где закрыто, он оставался
    /// без имён. У владельца 27.09 отвечают оба, 200 за 80 мс, так что
    /// смена ничего не стоит и там, где блокировки нет.
    /// </remarks>
    public string DnsServer { get; init; } = GoogleDns;

    /// <summary>Адрес Google, который работает по DoH и там, где 8.8.8.8 закрыт.</summary>
    public const string GoogleDns = "8.8.4.4";

    /// <summary>
    /// Выбирать апстрим самому — быстрейший по DoH после каждого обзора.
    /// </summary>
    /// <remarks>
    /// Отзыв пользователя 25.09: резолвер при знакомстве не выбирается,
    /// а подобрать его по задержке из места человека — дело программы.
    /// Выбор руками автовыбор выключает: иначе следующий обзор молча
    /// отменил бы решение человека.
    /// </remarks>
    public bool DnsAuto { get; init; }

    /// <summary>
    /// Game filter поверх пресета: десинк начала соединений игр.
    /// </summary>
    /// <remarks>
    /// Выключен по умолчанию: экспериментальный, перенесён с Flowseal
    /// по просьбе пользователя 25.09. Выключенный не меняет в запуске
    /// winws2 ничего. См. NetZapret.Zapret.GameFilter.
    /// </remarks>
    public bool GameFilter { get; init; }

    /// <summary>
    /// Вести журнал супервизора.
    /// </summary>
    /// <remarks>
    /// По умолчанию включён, и выключать его стоит с осторожностью: без
    /// журнала разбор сбоя сводится к догадкам. Выключатель заведён для тех,
    /// кого смущает рост файла — winws2 пишет строку на соединение.
    /// </remarks>
    public bool LogsEnabled { get; init; } = true;

    /// <summary>
    /// Предлагать перезапуск Discord после смены маршрута.
    /// </summary>
    /// <remarks>
    /// Discord запоминает голосовые серверы на сеанс, и до перезапуска ходит
    /// по-старому. Само собой это не делается никогда: перезапуск посреди
    /// звонка хуже задержки с применением.
    /// </remarks>
    public bool OfferDiscordRestart { get; init; }

    /// <summary>
    /// Держать автоподбор сервера подальше от отечественных выходов.
    /// </summary>
    /// <remarks>
    /// Включено по умолчанию. Автоподбор идёт по задержке и потому всегда
    /// сползает на ближайший сервер — свой же, — а через него не работает
    /// ровно то, ради чего туннель обычно и нужен: сервисы, закрывающиеся
    /// от страны. Выбрать отечественный вручную это не мешает.
    /// </remarks>
    public bool ForeignExitsOnly { get; init; } = true;

    /// <summary>
    /// Сначала стабильные: мигающие серверы (ServerHealth.Flaky) — мимо автоподбора
    /// и после стабильных в ленте и при сортировке.
    /// </summary>
    /// <remarks>
    /// Владелец 01.10: «нестабильные — это те, которые через раз работают».
    /// С 29.09 такие выводились из автоподбора всегда; теперь это выключатель
    /// на вкладке VPN, включённый по умолчанию — то есть прежнее поведение.
    /// </remarks>
    public bool StableFirst { get; init; } = true;

    /// <summary>
    /// Прятать VPN от российских приложений: имена, по которым они узнают
    /// свой адрес, — всегда напрямую (<see cref="Rules.VpnHiding"/>).
    /// </summary>
    /// <remarks>
    /// Выключено по умолчанию: в режиме «всё через VPN» человек, проверяя
    /// туннель на ifconfig.me, увидел бы домашний адрес и решил бы, что VPN
    /// не работает.
    /// </remarks>
    public bool HideVpnFromRussianApps { get; init; }

    /// <summary>
    /// Туннель через Cloudflare WARP вместо подписок (с 01.10 — выбор пути).
    /// </summary>
    /// <remarks>
    /// <para>
    /// До 01.10 WARP подмешивался к серверам подписок запасным. Владелец
    /// 01.10 развёл их: включённый WARP ставит подписки на паузу, и туннель
    /// идёт только через него (Warp.TunnelExits). Старые настройки переводятся
    /// один раз — см. <see cref="WarpIsPath"/>.
    /// </para>
    /// <para>
    /// Выключен по умолчанию: WARP выпускает трафик в ближайшем городе
    /// Cloudflare, из России — в Москве. От блокировок оператора он спасает,
    /// от отказов по стране — нет.
    /// </para>
    /// </remarks>
    public bool WarpEnabled { get; init; }

    /// <summary>
    /// Уводить трафик мимо туннеля, когда его выходы перестали отвечать.
    /// </summary>
    /// <remarks>
    /// <para>
    /// Жалоба владельца 20.09: «при падении серверов сделать так, чтоб вся
    /// остальная сеть не страдала». Движок при мёртвой подписке жив и трафик
    /// исправно принимает — а наружу тот не выходит; в режиме «всё через VPN»
    /// это вся сеть целиком. Обход переключает группу выбора на прямой выход
    /// и возвращает обратно, как только выход оживёт.
    /// </para>
    /// <para>
    /// <b>Это компромисс, а не бесплатное улучшение.</b> Трафик, который
    /// просили вести через туннель, пойдёт мимо — открыто и с домашнего
    /// адреса. Для обхода блокировок цена приемлема: закрытый сайт просто
    /// останется закрытым. Для скрытности — нет, и потому настройка есть.
    /// </para>
    /// <para>
    /// Включён по умолчанию, потому что беда, от которой он спасает, у людей
    /// случается, а скрытность программа и так нигде не обещает: она про
    /// обход блокировок. Срабатывание говорится вслух — в журнале и
    /// в состоянии, — а не делается тихо.
    /// </para>
    /// </remarks>
    public bool BypassWhenTunnelDead { get; init; } = true;

    /// <summary>
    /// Подменять выбранный руками сервер, пока он молчит.
    /// </summary>
    /// <remarks>
    /// <para>
    /// Владелец 30.09 — о заминках туннеля при выбранном сервере: «сделай это
    /// как настройку в настройках VPN». Выбранный сервер не ответил дважды
    /// подряд — на его место встаёт первый ответивший из автоподбора; сам он
    /// проверяется дальше и возвращается, ответив дважды подряд.
    /// </para>
    /// <para>
    /// Выключено по умолчанию: сервер выбирают руками и ради страны, а замена
    /// может оказаться в другой. Решать это за человека нельзя.
    /// </para>
    /// </remarks>
    public bool ReplaceSilentServer { get; init; }

    /// <summary>
    /// Как часто сторож проверяет подключённый сервер, секунды; 0 — не проверять.
    /// </summary>
    /// <remarks>
    /// Проверка — одно соединение через выход, который держит движок. Настройки
    /// проверки вынесены по слову владельца 28.09: «пусть каждый сам настраивает».
    /// Продавцы разные: одни держат нагрузку, другие (Trust, один вход на все
    /// страны) закрывают вход от частых проверок.
    /// </remarks>
    public int ExitCheckSeconds { get; init; } = 30;

    /// <summary>Как часто движок перемеряет все серверы автоподбора, минуты.</summary>
    /// <remarks>
    /// Этот замер бьёт по всем участникам разом. Было раз в минуту, 28.09 стало
    /// пять: 16 серверов Trust на одном входе получали пачку в 16 соединений.
    /// </remarks>
    public int FullCheckMinutes { get; init; } = 5;

    /// <summary>Сколько серверов с одного входа (адрес:порт) берёт автоподбор; 0 — всех.</summary>
    public int AutoPickPerEntry { get; init; } = 2;

    /// <summary>
    /// Серверы, которые человек убрал из автоподбора; выбрать их руками можно по-прежнему.
    /// </summary>
    /// <remarks>
    /// Владелец 29.09: ОБС у SecureWay отвечают через раз на домашней сети
    /// (замер: 2–3 из 5) и сбивают автоподбор, а на мобильной, вероятно, нужны.
    /// </remarks>
    public IReadOnlyList<string> AutoPickExcluded { get; init; } = Array.Empty<string>();

    /// <summary>
    /// Тема окна — имя папки в <c>themes\</c>: <c>dark</c>, <c>light</c> или чужая.
    /// </summary>
    /// <remarks>
    /// Строкой, а не логическим полем: тем может стать больше двух, и тогда
    /// <c>LightTheme: false</c> пришлось бы читать как «какая-то из
    /// остальных». Так и вышло 23.09 с темами художников — прежние значения
    /// <c>dark</c> и <c>light</c> остались именами встроенных папок.
    /// Неизвестная или непрошедшая проверку тема — тёмная.
    /// </remarks>
    public string? Theme { get; init; }

    /// <summary>
    /// Показывать картинку фона темы.
    /// </summary>
    /// <remarks>
    /// Настройки оформления — у человека, а не в теме (владелец, 23.09:
    /// «добавь настройки оформления, по типу размытие вкл/выкл»). Тема
    /// говорит, как задумано; здесь — что из задуманного он хочет видеть.
    /// </remarks>
    public bool ThemeBackgroundShown { get; init; } = true;

    /// <summary>Матовое стекло под карточками и меню, если у темы есть фон.</summary>
    public bool ThemeBlur { get; init; } = true;

    /// <summary>
    /// Насколько темнее задуманного затемнять фон: 0, 1 или 2 ступени.
    /// </summary>
    /// <remarks>
    /// Только темнее, не светлее: затемнение — то, чем тема проходит
    /// проверку читаемости, и ослабить его значило бы пустить нечитаемый
    /// текст в обход проверки.
    /// </remarks>
    public int ThemeDimSteps { get; init; }

    /// <summary>
    /// Размытие под меню трея: снимок экрана под ним, размытый.
    /// </summary>
    /// <remarks>
    /// Выключенное — меню прозрачно ровно настолько, насколько задано
    /// <see cref="TrayDensity"/>: сквозь него видно то, что под ним.
    /// Владелец 24.09: «добавь в настройки оформления вид трея».
    /// </remarks>
    public bool TrayBlur { get; init; } = true;

    /// <summary>
    /// Плотность подложки меню трея в процентах: 100 — сплошная.
    /// </summary>
    /// <remarks>
    /// Шестьдесят по умолчанию — близко к тому, что владелец видел
    /// и одобрил 24.09: размытое заметно, текст читается.
    /// </remarks>
    public int TrayDensity { get; init; } = 60;

    /// <summary>
    /// Шрифт всей программы поверх темы; <c>null</c> — шрифты темы.
    /// </summary>
    /// <remarks>
    /// Один на всё — интерфейс, заголовки и данные (владелец, 24.09: «лучше
    /// было бы, если бы на всю программу был один шрифт»). Прежде их было
    /// два, и шрифт данных не менялся вовсе. Цена известна: не моноширинный
    /// шрифт не держит цифры столбиком, адреса в таблицах чуть гуляют.
