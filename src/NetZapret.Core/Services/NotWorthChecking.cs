namespace NetZapret.Core.Services;

/// <summary>
/// Имена из наших списков, которые не идут в проверку блокировок.
/// </summary>
/// <remarks>
/// <para>
/// Из списков они не убраны и маршруты сохраняют. Список служит двум делам
/// разом — правилам маршрутизации и выбору целей проверки, — и вычеркнуть
/// имя ради тишины в отчёте значило бы сломать работающий маршрут.
/// Здесь только второе: что не проверяем.
/// </para>
/// <para>
/// Набор общий для консоли и окна, и это не удобство. Держать его двумя
/// копиями уже пробовали: у окна лежал голый перечень имён без единой
/// строки о том, почему они там, а у консоли — тот же перечень с разбором.
/// Две такие копии обязаны совпадать и однажды разойдутся, причём
/// разойдутся молча.
/// </para>
/// </remarks>
public static class NotWorthChecking
{
    public static bool Contains(string host) => Names.Contains(host);

    public static IReadOnlyCollection<string> All => Names;

    private static readonly HashSet<string> Names = new(StringComparer.OrdinalIgnoreCase)
    {
        // Единственное оставшееся зеркало из старых. Остальные — twitter.com,
        // twitch.com, ubi.com, claude.com, telegram.me — из списков либо
        // убраны, либо опущены ниже проверяемых, так что глушить их больше
        // нечего. Это зеркало живёт в riot-valorant.txt, где договорено
        // не трогать ничего: цена ошибки там выше обычной.
        "riotgames.es",

        // Снято с показа по решению владельца проекта: у него они работают,
        // а отчёт про них третий прогон подряд утверждает обратное.
        //
        // Цена решения известна и записана здесь, чтобы не забылась:
        // itch.zone и rutor.info были двумя из четырёх улик в догадке о том,
        // что десинк портит рукопожатие, уходящее в туннель. Проверять её
        // теперь придётся по itch.io и rutracker.org, которые в отчёте
        // остались.
        "itch.zone",
        "rutor.info",
        "valorant.com",

        // Зеркало proton.me, и снято по той же причине: у владельца оно
        // работает, а отчёт звал его «закрыт полностью» — при том что
        // proton.me в той же таблице строкой ниже «доступен».
        //
        // Из proton.txt не убрано намеренно: файл прямо поясняет, что
        // protonmail.com и protonmail.ch — прежние имена, по которым до сих
        // пор ходят почтовые клиенты, настроенные годы назад. Маршрут им
        // нужен, проверка — нет.
        "protonmail.com",

        // Тот же хост, что whatsapp.net: замер через DoH 2026-09-16 даёт
        // обоим апексам 31.13.72.52, и www.whatsapp.com ведёт туда же через
        // mmx-ds.cdn.whatsapp.net. Две строки об одном адресе — это два
        // шанса разойтись по случайности, а не два замера.
        //
        // Оставлен .net, а не .com: под ним живёт то, чем пользуется само
        // приложение — g.whatsapp.net, mmg.whatsapp.net, media-*.cdn. И там
        // же оговорка из whatsapp.txt, которая остаётся в силе: проверке
        // по 443 верить нельзя вовсе, клиент ходит по своим адресам
        // и порту 5222.
        "whatsapp.com",

        // Апекс потоковой зоны Netflix — не хост, с которого идёт видео:
        // поток отдают узлы под ним, *.oca.nflxvideo.net. Сам апекс
        // разрешается в адреса AWS, а те рукопожатие отвергают и напрямую,
        // без движков: замер 2026-09-26, curl на 18.236.7.30 —
        // SEC_E_INTERNAL_ERROR. В каждом отчёте выходило «наше приветствие
        // TLS отвергнуто» о сайте, который никто не открывает. Из netflix.txt
        // не убран: маршрут нужен зоне, а не апексу.
        "nflxvideo.net",

        // То же с SoundCloud: поток и обложки идут с cf-media.sndcdn.com
        // и i1.sndcdn.com, а голое имя рукопожатия не завершает. Замер
        // 2026-09-26: 108.156.22.126 под именем cf-media отвечает за 0,06 с,
        // под именем sndcdn.com молчит шесть секунд — на всех четырёх
        // честных адресах; порт 80 отвечает сразу. В отчёте это было
        // «DPI по TLS» на секции soundcloud при исправно играющем плеере.
        "sndcdn.com",

        // Голые зоны сетей доставки. Записи A у них нет и не было: работают
        // только поддомены, а сама зона существует ради сопоставления
        // по суффиксу. Проверять там нечего, и строки «нет адреса у имени»
        // в каждом отчёте — чистый шум. Список измерен, а не составлен
        // на глаз: 1.1.1.1, 2026-09-04, каждое имя опрошено на запись A.
        "cdninstagram.com",
        "tiktokcdn.com",
        "licdn.com",
        "nocookie.net",
        "cloudfront.net",
        "ooklaserver.net",
        "cdnst.net",
        "rgpub.io",
        "ytimg.com",
        "ggpht.com",
        "twimg.com",
        "discordapp.net",
        "rbxcdn.com",
        "steamstatic.com",
        "githubusercontent.com",
    };
}
