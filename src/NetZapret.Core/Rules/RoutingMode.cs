namespace NetZapret.Core.Rules;

/// <summary>
/// Куда отправить трафик соединения.
/// </summary>
public enum RoutingMode
{
    /// <summary>
    /// Не вмешиваться: соединение идёт по обычному маршруту ОС.
    /// </summary>
    Direct = 0,

    /// <summary>
    /// Через прокси-движок (sing-box), то есть в TUN-интерфейс.
    /// </summary>
    Proxy = 1,

    /// <summary>
    /// Отдать на откуп Zapret'у (WinDivert-десинк).
    /// <para>
    /// Механически сегодня это то же самое, что <see cref="Direct"/> — NetZapret
    /// такие пакеты не трогает, а winws2 уже висит на них своим WinDivert-фильтром.
    /// Режим выделен отдельно намеренно: во-первых, он несёт намерение пользователя
    /// и различает "просто мимо" и "должно чиниться десинком" в статистике; во-вторых,
    /// когда появится модуль управления Zapret'ом, именно эти правила будут
    /// компилироваться в его hostlist'ы.
    /// </para>
    /// <para>
    /// Важное следствие: <see cref="Desync"/> НИКОГДА не должен приводить к заходу
    /// трафика в TUN — иначе десинк будет применяться к переоткрытому сокету sing-box,
    /// а не к исходному потоку приложения.
    /// </para>
    /// </summary>
    Desync = 2,
}
