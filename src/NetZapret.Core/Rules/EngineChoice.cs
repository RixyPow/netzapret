namespace NetZapret.Core.Rules;

/// <summary>
/// Что поднято и насколько широко работает туннель.
/// </summary>
/// <remarks>
/// <para>
/// Задумка владельца, 21.09: вместо одного поля с пятью значениями —
/// два выключателя движков, winws2 и туннель. Прежние режимы из них
/// выводятся, а не задаются.
/// </para>
/// <para>
/// Разница не косметическая. Пять режимов пришли по одному, каждый
/// под свой случай, и объяснить разницу между «всё через VPN» и «всё
/// без исключений» удавалось только примером. Два выключателя отвечают
/// на вопрос, который человек и задаёт: что у меня сейчас работает.
/// </para>
/// <para>
/// Охват туннеля сперва был третьей настройкой, и это оказалось лишним:
/// он выводится из тех же двух выключателей. Туннель без десинка
/// забирает всё — чинить имена больше нечем; вместе с десинком обязан
/// оставлять тому работу. Единственное сочетание, которое добавлял
/// отдельный выключатель, было тем самым, на которое приходилось
/// жаловаться.
/// </para>
/// </remarks>
public sealed record EngineChoice
{
    /// <summary>Поднимать ли winws2.</summary>
    public bool Desync { get; init; } = true;

    /// <summary>Поднимать ли туннель.</summary>
    public bool Tunnel { get; init; } = true;

    /// <summary>
    /// Туннель забирает весь трафик, а не только названное в маршрутах.
    /// </summary>
    /// <remarks>
    /// <para>
    /// Выводится, а не задаётся — поправка владельца 21.09, и она верна.
    /// Туннель без десинка забирает всё по смыслу: чинить имена больше
    /// нечем, и выпускать что-либо напрямую незачем. А вместе с десинком
    /// он обязан оставлять тому работу — иначе winws2 крутится вхолостую.
    /// </para>
    /// <para>
    /// Настройкой это было полчаса и было лишним: отдельный выключатель
    /// позволял собрать ровно одно новое сочетание — оба движка и туннель,
    /// забравший всё, — то самое, на которое приходилось жаловаться.
    /// Выведенное, оно этого состояния просто не имеет.
    /// </para>
    /// <para>
    /// «Как обычный VPN» — слова владельца. Домашняя сеть при этом
    /// остаётся снаружи всегда: завернув <c>192.168.х.х</c> в туннель,
    /// оборвали бы роутер, принтер и сетевой диск. Это условие работы
    /// машины, а не настройка.
    /// </para>
    /// </remarks>
    /// <remarks>
    /// С 23.09 забирает всё и тогда, когда исключения игнорируются: всё
    /// идёт в туннель, и узкий охват оставил бы за бортом ровно то, что
    /// настройка туда отправила.
    /// </remarks>
    public bool TunnelTakesAll => Tunnel && (!Desync || IgnoreExclusions);

    /// <summary>
    /// Отправлять в туннель всё, включая «напрямую» и «десинк».
    /// </summary>
    /// <remarks>
    /// <para>
    /// Таблица владельца 23.09: «напрямую — VPN, десинк — VPN, VPN — VPN».
    /// Прежде настройка отменяла одно правило, на российские сети, а прочие
    /// исключения оставляла, — владелец просил другого.
    /// </para>
    /// <para>
    /// Цена та же и названа в окне: российские сервисы увидят зарубежный
    /// адрес, банки и госуслуги потребуют подтверждений, часть откажет.
    /// Домашняя сеть остаётся снаружи всегда — это условие работы машины.
    /// </para>
    /// <para>
    /// Действует только при поднятом туннеле: без него везти некуда.
    /// </para>
    /// </remarks>
    public bool IgnoreExclusions { get; init; }

    /// <summary>
    /// Поднимается ли десинк на деле.
    /// </summary>
    /// <remarks>
    /// Выключатель может стоять, а работы у десинка не быть: при
    /// игнорируемых исключениях всё уходит в туннель, и winws2 видел бы
    /// только его собственные соединения с сервером. Хуже чем вхолостую —
    /// секция пресета, совпавшая с именем-маскировкой сервера, рвала бы
    /// сам туннель.
    /// </remarks>
    public bool DesyncRuns => Desync && !(Tunnel && IgnoreExclusions);

    /// <summary>Работает ли хоть что-нибудь.</summary>
    public bool Anything => Desync || Tunnel;

    /// <summary>
    /// Чем пойдёт маршрут книги при этих выключателях — таблица владельца
    /// от 23.09 одной функцией.
    /// </summary>
    /// <remarks>
    /// <para>
    /// Сама таблица исполняется в двух местах: конфигом sing-box (через
    /// <see cref="Mode"/>) и списком исключений winws2. Здесь она названа
    /// словами — для ответа «куда пойдёт это имя», который книга дать
    /// не может: «через VPN» при выключенном туннеле идёт напрямую.
    /// </para>
    /// <para>
    /// Совпадение с исполнением сторожит ModeTableTests: разойдись они,
    /// ответ «куда пойдёт» стал бы враньём.
    /// </para>
    /// <para>
    /// <paramref name="tunnelUp"/> — поднимется ли туннель на деле:
    /// выключатель без выхода TUN не даёт.
    /// </para>
    /// </remarks>
    public RoutingMode Effective(RoutingMode book, bool tunnelUp)
    {
        if (!tunnelUp)
        {
            // Везти некуда: VPN идёт напрямую, десинк — десинку, если поднят.
            return book == RoutingMode.Desync && DesyncRuns ? RoutingMode.Desync : RoutingMode.Direct;
        }

        if (IgnoreExclusions)
            return RoutingMode.Proxy;

        return book switch
        {
            RoutingMode.Direct => RoutingMode.Direct,
            RoutingMode.Desync => DesyncRuns ? RoutingMode.Desync : RoutingMode.Proxy,
            _ => RoutingMode.Proxy,
        };
    }

    /// <summary>
    /// Прежний режим — для того, что ещё понимает только его.
    /// </summary>
    /// <remarks>
    /// Выводится, а не хранится. Конфиг движка, отчёты и правила говорят
    /// на языке режимов, и переводить их все разом значило бы менять
    /// полпрограммы одной правкой.
    /// </remarks>
    /// <remarks>
    /// <para>
    /// Режимы и есть таблица владельца от 23.09, строка за строкой:
    /// </para>
    /// <list type="bullet">
    /// <item>десинк — напрямую, десинк, VPN идёт напрямую
    /// (<see cref="OperatingMode.DesyncOnly"/>: туннеля нет, а «VPN»
    /// выводится из-под десинка списком исключений);</item>
    /// <item>десинк и туннель — всё как в книге
    /// (<see cref="OperatingMode.Selective"/>);</item>
    /// <item>только туннель — напрямую остаётся, десинк уходит в VPN
    /// (<see cref="OperatingMode.ProxyAll"/>: в конфиг идут одни прямые
    /// правила, остальное забирает final);</item>
    /// <item>игнорировать исключения — всё в VPN
    /// (<see cref="OperatingMode.ProxyStrict"/>: правил нет вовсе).</item>
    /// </list>
    /// </remarks>
    public OperatingMode Mode => (Desync, Tunnel) switch
    {
        (false, false) => OperatingMode.Off,
        (true, false) => OperatingMode.DesyncOnly,
        (_, true) when IgnoreExclusions => OperatingMode.ProxyStrict,
        (true, true) => OperatingMode.Selective,
        (false, true) => OperatingMode.ProxyAll,
    };

    /// <summary>
    /// Чем это сочетание нехорошо; пусто — всё в порядке.
    /// </summary>
    /// <remarks>
    /// <para>
    /// Два независимых выключателя позволяют собрать сочетание, которое
    /// выглядит разумно и работает не так, как кажется. Сказать об этом
    /// должно окно, а не человек через неделю разбора.
    /// </para>
    /// <para>
    /// Молчать о таком — та же беда, что была с прибитым в hosts именем:
    /// всё зелёное, всё настроено, и ничего не работает.
    /// </para>
    /// </remarks>
    public string? Complaint
    {
        get
        {
            if (!Anything)
                return "ничего не поднято — весь трафик идёт напрямую, как без программы";

            if (Tunnel && IgnoreExclusions)
            {
                return "исключения не действуют: российские сервисы уйдут в туннель "
                    + "и увидят зарубежный адрес — банки и госуслуги потребуют "
                    + "подтверждений, часть откажет"
                    + (Desync ? "; десинку при этом нечего чинить, и он не поднимется" : string.Empty);
            }

            return null;
        }
    }

    /// <summary>Как это называется словами.</summary>
    public string Describe() => (Desync, Tunnel) switch
    {
        (false, false) => "ничего не поднято",
        (true, false) => "только десинк",
        (_, true) when IgnoreExclusions => "только VPN, весь трафик без исключений",
        (false, true) => "только VPN, весь трафик",
        (true, true) => "десинк и VPN по маршрутам",
    };

    /// <summary>
    /// Собирает выбор из прежнего режима.
    /// </summary>
    /// <remarks>
    /// <para>
    /// Нужен для перехода: у людей в настройках лежит режим, и прочитать
    /// его надо так, чтобы ничего не изменилось само.
    /// </para>
    /// <para>
    /// Оборот точен для четырёх режимов из пяти. «Без исключений»
    /// возвращается как «всё через туннель» с включённой настройкой —
    /// потому и заводилась настройка. Прежнее поведение при этом
    /// сохраняется, меняется только то, чем оно записано.
    /// </para>
    /// <para>
    /// Десинк при «всё через туннель» выключен, и это не мелочь. TUN
    /// забирает весь трафик, до WinDivert не доходит ничего, и оставленный
    /// включённым winws2 работал бы вхолостую — а выглядел бы работающим.
    /// Так и записано в таблице владельца: «винвс выключен».
    /// </para>
    /// </remarks>
    public static EngineChoice FromMode(OperatingMode mode) => mode switch
    {
        OperatingMode.Off => new EngineChoice { Desync = false, Tunnel = false },
        OperatingMode.DesyncOnly => new EngineChoice { Desync = true, Tunnel = false },

        OperatingMode.ProxyAll => new EngineChoice { Desync = false, Tunnel = true },

        OperatingMode.ProxyStrict => new EngineChoice
        {
            Desync = false,
            Tunnel = true,
            IgnoreExclusions = true,
        },

        _ => new EngineChoice(),
    };
}
