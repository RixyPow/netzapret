namespace NetZapret.Core.Rules;

/// <summary>Куда отправить имя.</summary>
/// <remarks>
/// Ключи латиницей намеренно — файл предназначен для обмена, и кириллица
/// в ключах переживает пересылку хуже. В окне при этом остаются русские
/// слова: «напрямую» и <c>direct</c> — одно и то же, разница лишь в том,
/// где написано.
/// </remarks>
public enum RouteChoice
{
    /// <summary>Мимо туннеля и мимо десинка.</summary>
    Direct,

    /// <summary>Мимо туннеля, чинится десинком.</summary>
    Desync,

    /// <summary>Через туннель.</summary>
    Vpn,

    /// <summary>
    /// Прибить адрес в <c>hosts</c>.
    /// </summary>
    /// <remarks>
    /// <para>
    /// Четвёртый маршрут, а не отдельное поле — решение владельца 21.09.
    /// Возражение было в том, что пин привязан к машине; оно верно про
    /// адрес и неверно про намерение. <c>tmdb: pin</c> означает «это имя
    /// надо прибить», а не «прибить вот сюда»: на другой машине адрес
    /// найдётся свой.
    /// </para>
    /// <para>
    /// Сам файл <c>hosts</c> этим не правится. Строка — рекомендация,
    /// которую показывают маршруты; правка системного файла остаётся
    /// отдельным действием с отдельным согласием.
    /// </para>
    /// </remarks>
    Pin,
}

/// <summary>Одна запись книги маршрутов.</summary>
public sealed record RouteEntry
{
    /// <summary>Имя группы либо отдельный домен.</summary>
    public required string Name { get; init; }

    public required RouteChoice Choice { get; init; }

    /// <summary>
    /// Рецепт десинка; пусто — решает пресет.
    /// </summary>
    /// <remarks>
    /// Только при <see cref="RouteChoice.Desync"/>. У прочих маршрутов
    /// смысла не имеет: через туннель рецепт не применяется, а прибитое
    /// имя из-под десинка выводится вовсе.
    /// </remarks>
    public string? Recipe { get; init; }

    /// <summary>Группа это или одно имя.</summary>
    /// <remarks>
    /// По точке: <c>discord</c> — группа, <c>discord.com</c> — домен.
    /// Правило грубое, зато его можно объяснить в одну строку, а домена
    /// без точки не бывает.
    /// </remarks>
    public bool IsGroup => !Name.Contains('.');
}

/// <summary>
/// Книга маршрутов: что куда ходит.
/// </summary>
/// <remarks>
/// <para>
/// Задумка владельца, 21.09. Сейчас судьба имени собирается из пяти
/// источников: <c>rules.yaml</c>, <c>rules.user.yaml</c>, секции пресета
/// Zapret, пины в <c>hosts</c> и выводимый из первых двух список
/// исключений десинка. Порядок между ними нигде не записан — он в коде.
/// </para>
/// <para>
/// Отсюда все загадки 21.09: Instagram был прибит в <c>hosts</c> и потому
/// выведен из-под десинка целиком, рецепт из каталога не находился,
/// потому что искали в пресете. Каждый раз разбор упирался в несведённые
/// источники.
/// </para>
/// <para>
/// Главное свойство книги — <b>переносимость</b>. Она не трогает ни
/// пресеты winws2, ни конфиг туннеля: это отдельно записанное «как должны
/// ходить маршруты», и один файл работает и с Universal V9, и с Default
/// v1. Отсюда же ввоз и вывоз: такой файл можно отдать другому человеку.
/// </para>
/// <para>
/// Группы — решение третьего вопроса. У владельца восемьдесят восемь
/// правил, и почти все на списки каталога; без групп перенос развернул бы
/// их в несколько сотен строк отдельных имён.
/// </para>
/// </remarks>
public sealed record RouteBook
{
    /// <summary>Записи в порядке файла.</summary>
    public IReadOnlyList<RouteEntry> Entries { get; init; } = [];

    /// <summary>
    /// Свои группы: имя → домены.
    /// </summary>
    /// <remarks>
    /// Для того, чего нет в каталоге. Каталожные группы сюда не
    /// переписываются: они едут вместе с программой, и дублировать
    /// их в файле значило бы раздуть его до сотен строк ради того,
    /// что и так есть на обеих машинах.
    /// </remarks>
    public IReadOnlyDictionary<string, IReadOnlyList<string>> Groups { get; init; } =
        new Dictionary<string, IReadOnlyList<string>>(StringComparer.OrdinalIgnoreCase);

    /// <summary>
    /// Противоречия: одно имя названо дважды по-разному.
    /// </summary>
    /// <remarks>
    /// <para>
    /// Самое ценное, что даёт книга, и ради чего стоило её заводить.
    /// Пин и VPN несовместимы: прибитое имя не получает fakeip, а без
    /// fakeip движок не заводит его в туннель — правило «через VPN»
    /// на прибитое имя не делает ничего. Вдобавок прибитое выводится
    /// из-под десинка.
    /// </para>
    /// <para>
    /// 21.09 это стоило часа разбора: Instagram был прибит, десинк
    /// к нему не применялся ни разу, а проверка рецептов показывала,
    /// что рецепт работает, — она поднимает свой winws2 без списка
    /// исключений. Книга делает противоречие высказанным при чтении
    /// файла, а не через час.
    /// </para>
    /// </remarks>
    public IReadOnlyList<RouteClash> Clashes { get; init; } = [];

    public static RouteBook Empty { get; } = new();
}

/// <summary>Одно имя названо дважды и по-разному.</summary>
public sealed record RouteClash
{
    public required string Name { get; init; }

    public required RouteChoice First { get; init; }

    public required RouteChoice Second { get; init; }

    /// <summary>Чем это кончится на деле — словами.</summary>
    public required string Outcome { get; init; }
}
