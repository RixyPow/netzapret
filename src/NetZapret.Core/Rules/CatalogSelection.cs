namespace NetZapret.Core.Rules;

/// <summary>
/// Проверяет, что выбор в каталоге вообще что-то даёт.
/// </summary>
/// <remarks>
/// <para>
/// Заведено по случаю, где настройка выглядела применённой и не делала
/// ничего. В настройках стояло семь выбранных сервисов, набор адресов был
/// не выбран, и на выходе получалось ноль подстановок: сервисы вида
/// <c>dns</c> берут адрес из набора, и без него запрос к базе попросту
/// не выполняется.
/// </para>
/// <para>
/// Человек при этом видел семь галочек и был уверен, что каталог работает.
/// Разубедить его могло только сообщение, и вот оно.
/// </para>
/// </remarks>
public static class CatalogSelection
{
    /// <summary>
    /// Почему выбор не дал адресов; <c>null</c> — всё в порядке.
    /// </summary>
    /// <param name="services">Сколько сервисов отмечено в настройках.</param>
    /// <param name="profile">Выбранный набор; пусто — не выбран.</param>
    /// <param name="answers">Сколько адресов вышло на деле.</param>
    public static string? Explain(int services, string? profile, int answers)
    {
        if (services == 0 || answers > 0)
            return null;

        return string.IsNullOrWhiteSpace(profile)
            ? $"выбрано сервисов: {services}, но набор адресов не выбран — " +
              "подстановок не будет. Наборы перечислены там же, где сервисы."
            : $"выбрано сервисов: {services}, набор «{profile}» — но адресов " +
              "для них в нём нет. Возьмите другой набор.";
    }
}
