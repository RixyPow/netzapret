namespace NetZapret.Zapret;

/// <summary>
/// Разбор имени на зоны.
/// </summary>
public static class HostNames
{
    /// <summary>
    /// Само имя, затем его предки — до двухуровневого включительно.
    /// </summary>
    /// <remarks>
    /// <para>
    /// Заведено для пробы рецептов. Имя, на котором проверяют, может
    /// не разрешаться вовсе, и это не помеха: фильтр читает его из приветствия
    /// TLS, а не из DNS. Но соединиться всё же надо с кем-то — и адрес берётся
    /// у ближайшего предка, который разрешается: он в той же зоне и стоит
    /// за той же сетью доставки.
    /// </para>
    /// <para>
    /// Нужно это там, где у зоны нет ни одного постоянного имени. Голосовые
    /// серверы Discord выдаются под звонок, и <c>frankfurt1234.discord.media</c>
    /// сегодня отвечает пустотой у любого резолвера — при том что сама зона
    /// закрыта и проверять её чем-то надо.
    /// </para>
    /// <para>
    /// На двух метках обход кончается. Дальше пошли бы <c>media</c>, <c>com</c>
    /// и прочие общие суффиксы: за ними либо не стоит никто, либо стоит реестр
    /// зоны, не имеющий к нашему имени отношения. Адрес реестра дал бы замер
    /// о постороннем узле — хуже, чем никакого.
    /// </para>
    /// </remarks>
    public static IEnumerable<string> ZoneChain(string host)
    {
        var name = host?.Trim().Trim('.') ?? string.Empty;

        if (name.Length == 0)
            yield break;

        while (true)
        {
            yield return name;

            int dot = name.IndexOf('.');

            if (dot < 0)
                yield break;

            var parent = name[(dot + 1)..];

            // Предок без точки — это уже общий суффикс, а не чья-то зона.
            if (!parent.Contains('.'))
                yield break;

            name = parent;
        }
    }
}
