namespace NetZapret.Proxy;

/// <summary>Что сделать с туннелем по итогам очередной проверки.</summary>
public enum BypassAction
{
    /// <summary>Ничего: положение не изменилось.</summary>
    Keep,

    /// <summary>Увести трафик мимо туннеля — выходы не отвечают.</summary>
    Engage,

    /// <summary>Вернуть в туннель — выход ожил.</summary>
    Release,
}

/// <summary>
/// Обход туннеля, пока его выходы мертвы.
/// </summary>
/// <remarks>
/// <para>
/// Жалоба владельца: «при падении серверов сделать так, чтоб вся остальная
/// сеть не страдала». Беда настоящая и своя, отдельная от той, что чинилась
/// в 0.6.3. Там супервизор перестал гасить исправный движок из-за мёртвой
/// подписки — движок жив, но трафик, направленный в туннель, всё равно
/// уходит в никуда. В режиме «всё через VPN» это вся сеть целиком.
/// </para>
/// <para>
/// Лечение: переключить группу выбора на <c>direct</c> через Clash API.
/// Мгновенно, без перезапуска и без пересборки конфига — тем же движением,
/// каким человек закрепляет сервер руками.
/// </para>
/// <para>
/// <b>Это осознанный компромисс, а не бесплатное улучшение.</b> Трафик,
/// который человек просил вести через туннель, пойдёт мимо него — открыто
/// и с домашнего адреса. Для обхода блокировок цена приемлема: закрытый
/// сайт просто останется закрытым, как и был. Для скрытности — нет, и
/// потому обход отключается настройкой, а его срабатывание говорится вслух,
/// а не делается тихо.
/// </para>
/// <para>
/// Порог не единица. Одна неудачная проверка случается и при исправном
/// туннеле — сеть моргнула, выход перегружен, — и уводить по ней значило бы
/// метаться мимо туннеля и обратно несколько раз в час.
/// </para>
/// </remarks>
public sealed class TunnelBypass
{
    /// <summary>Тег прямого выхода — он же участник группы выбора.</summary>
    public const string DirectTag = "direct";

    /// <summary>Сколько проверок подряд должны провалиться до обхода.</summary>
    /// <remarks>
    /// Три, как и у вывода мёртвых серверов из автоподбора. Число одно
    /// не случайно: обе проверки отвечают на один вопрос — «выход мёртв
    /// или моргнул», — и разные пороги означали бы два разных ответа.
    /// </remarks>
    public const int FailuresBeforeBypass = 3;

    private int _failures;

    /// <summary>Включён ли обход прямо сейчас.</summary>
    public bool Engaged { get; private set; }

    /// <summary>Сколько проверок подряд провалилось.</summary>
    public int Failures => _failures;

    /// <summary>
    /// Учесть исход проверки и сказать, что делать.
    /// </summary>
    /// <param name="tunnelWorks">
    /// Проходит ли трафик через туннель. Пока обход включён, это ответ
    /// замера самих выходов, а не общей проверки: та при обходе идёт
    /// через <c>direct</c> и удалась бы всегда, вернув нас в мёртвый
    /// туннель на следующем же шаге — и так по кругу.
    /// </param>
    public BypassAction Observe(bool tunnelWorks)
    {
        if (tunnelWorks)
        {
            _failures = 0;

            if (!Engaged)
                return BypassAction.Keep;

            Engaged = false;
            return BypassAction.Release;
        }

        // Счётчик не растёт без надобности: при включённом обходе он своё
        // дело сделал, и копить дальше незачем — переполнение не грозит,
        // но число в журнале становится бессмысленно большим.
        if (Engaged)
            return BypassAction.Keep;

        if (++_failures < FailuresBeforeBypass)
            return BypassAction.Keep;

        Engaged = true;
        return BypassAction.Engage;
    }

    /// <summary>
    /// Забыть всё.
    /// </summary>
    /// <remarks>
    /// Нужен при перезапуске движка: новый процесс поднимается с группой,
    /// указывающей на автоподбор, и память о прежнем обходе заставила бы
    /// нас считать, что трафик уже уведён, когда он идёт в туннель.
    /// </remarks>
    public void Forget()
    {
        _failures = 0;
        Engaged = false;
    }

    /// <summary>Куда переключить группу выбора.</summary>
    public string TargetFor(BypassAction action, string latencyTag) => action switch
    {
        BypassAction.Engage => DirectTag,
        _ => latencyTag,
    };
}
